function bindLab7() {
  const root = document.querySelector(".lab7");
  if (!root || root.dataset.bound) return;
  root.dataset.bound = "1";

  root.addEventListener("click", (event) => {
    const horizon = event.target.closest("[data-bia]");
    if (horizon) {
      const id = horizon.dataset.bia;
      root.querySelectorAll("[data-bia]").forEach((chip) => {
        const on = chip.dataset.bia === id;
        chip.classList.toggle("is-on", on);
        chip.setAttribute("aria-pressed", on ? "true" : "false");
      });
      root.querySelectorAll("[data-h]").forEach((cell) => {
        const hot = id !== "all" && cell.dataset.h === id;
        const dim = id !== "all" && cell.dataset.h !== id;
        cell.classList.toggle("is-hot", hot);
        cell.classList.toggle("is-dim", dim);
      });
      return;
    }
    const scenario = event.target.closest("[data-scenario-filter]");
    if (!scenario) return;
    const id = scenario.dataset.scenarioFilter;
    root.querySelectorAll("[data-scenario-filter]").forEach((chip) => {
      const on = chip.dataset.scenarioFilter === id;
      chip.classList.toggle("is-on", on);
      chip.setAttribute("aria-pressed", on ? "true" : "false");
    });
    root.querySelectorAll("[data-scenario]").forEach((card) => {
      card.hidden = id !== "all" && card.dataset.scenario !== id;
    });
  });
}

