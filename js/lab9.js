function lab9PrioClass(prio) {
  if (prio === "critical") return "sev sev-critical";
  if (prio === "high") return "sev sev-high";
  if (prio === "mid") return "sev sev-mid";
  return "sev sev-low";
}

function lab9Rule(impact, urgency) {
  return LAB9.rules.find((item) => item.impact === String(impact) && item.urgency === String(urgency));
}

function lab9Sync(item) {
  const rule = lab9Rule(item.impact, item.urgency);
  item.cell = rule.cell;
  item.prio = rule.prio;
  item.label = rule.label;
}

function lab9Stepper(kind, item) {
  const value = Number(item[kind]);
  const down = kind === "impact" ? "Әсерді кішірейту" : "Жеделдікті кішірейту";
  const up = kind === "impact" ? "Әсерді үлкейту" : "Жеделдікті үлкейту";
  return `
    <span class="score-step">
      <button type="button" data-step="${kind}" data-dir="-1" data-inc="${item.n}" aria-label="${down}" ${value <= 1 ? "disabled" : ""}>−</button>
      <strong data-field="${kind}">${value}</strong>
      <button type="button" data-step="${kind}" data-dir="1" data-inc="${item.n}" aria-label="${up}" ${value >= 3 ? "disabled" : ""}>+</button>
    </span>`;
}

function lab9FmtMin(value) {
  if (!Number.isFinite(value)) return "—";
  const mins = Math.round(value * 10) / 10;
  const shown = Number.isInteger(mins) ? String(mins) : mins.toFixed(1);
  if (mins < 60) return `${shown} мин`;
  const whole = Math.floor(mins);
  const h = Math.floor(whole / 60);
  const rest = whole % 60;
  const clock = rest ? `${h} сағ ${rest} мин` : `${h} сағ`;
  return `${shown} мин (${clock})`;
}

function bindLab9() {
  const root = document.querySelector(".lab9");
  if (!root || root.dataset.bound) return;
  root.dataset.bound = "1";

  const note = root.querySelector("#inc-note");
  const grid = root.querySelector("#prio-grid");
  const summary = root.querySelector("#inc-summary");
  const hot = root.querySelector("#inc-hot");
  let filterMode = "all";
  let filterValue = "all";

  function paintIncident(item) {
    const row = root.querySelector(`#inc-table tr[data-inc="${item.n}"]`);
    if (!row) return;
    row.dataset.prio = item.prio;
    row.dataset.cell = item.cell;
    row.querySelectorAll("[data-step]").forEach((button) => {
      const value = Number(item[button.dataset.step]);
      const dir = Number(button.dataset.dir);
      button.disabled = dir < 0 ? value <= 1 : value >= 3;
    });
    row.querySelectorAll("[data-field]").forEach((field) => {
      field.textContent = item[field.dataset.field];
    });
    const badge = row.querySelector("[data-prio-badge]");
    if (badge) {
      badge.className = lab9PrioClass(item.prio);
      badge.textContent = item.label;
    }
  }

  function paintMatrix() {
    if (!grid) return;
    grid.querySelectorAll("[data-cell]").forEach((button) => {
      const hits = LAB9.incidents.filter((item) => item.cell === button.dataset.cell);
      const small = button.querySelector("small");
      if (small) small.textContent = `№ ${hits.length ? hits.map((item) => item.n).join(", ") : "—"}`;
    });
  }

  function paintCounts() {
    const counts = LAB9.incidents.reduce((acc, item) => {
      acc[item.prio] = (acc[item.prio] || 0) + 1;
      return acc;
    }, {});
    if (summary) {
      summary.textContent = `${counts.critical || 0} сыни, ${counts.high || 0} жоғары, ${counts.mid || 0} орташа, ${counts.low || 0} төмен.`;
    }
    if (hot) hot.textContent = String((counts.critical || 0) + (counts.high || 0));
  }

  function applyIncidents(mode, value) {
    filterMode = mode;
    filterValue = value;
    root.querySelectorAll("[data-inc-filter]").forEach((chip) => {
      const on = mode === "prio" ? chip.dataset.incFilter === value : mode === "all" && chip.dataset.incFilter === "all";
      chip.classList.toggle("is-on", on);
      chip.setAttribute("aria-pressed", on ? "true" : "false");
    });
    if (grid) {
      grid.querySelectorAll("[data-cell]").forEach((cell) => {
        const on = mode === "cell" && cell.dataset.cell === value;
        cell.classList.toggle("is-on", on);
        cell.setAttribute("aria-pressed", on ? "true" : "false");
      });
    }
    let shown = 0;
    root.querySelectorAll("#inc-table tbody tr").forEach((row) => {
      const hide =
        (mode === "prio" && row.dataset.prio !== value) ||
        (mode === "cell" && row.dataset.cell !== value);
      row.hidden = hide;
      if (!hide) shown += 1;
    });
    if (!note) return;
    if (mode === "all") {
      note.textContent = `${LAB9.incidents.length} инцидент. Басымдықты немесе матрица ұяшығын таңдаңыз.`;
      return;
    }
    if (mode === "cell") {
      const rule = LAB9.rules.find((item) => item.cell === value);
      note.textContent = rule
        ? `Ұяшық әсер ${rule.impact} × жеделдік ${rule.urgency}: ${rule.label}. ${shown} инцидент.`
        : `${shown} инцидент.`;
      return;
    }
    const label = { critical: "Сыни", high: "Жоғары", mid: "Орташа", low: "Төмен" }[value] || value;
    note.textContent = `${label}: ${shown} инцидент.`;
  }

  function applyScenario(id) {
    root.querySelectorAll("[data-scenario-filter]").forEach((chip) => {
      const on = chip.dataset.scenarioFilter === id;
      chip.classList.toggle("is-on", on);
      chip.setAttribute("aria-pressed", on ? "true" : "false");
    });
    root.querySelectorAll(".playbook").forEach((card) => {
      card.hidden = id !== "all" && card.dataset.scenario !== id;
    });
  }

  function readMetrics() {
    return [...root.querySelectorAll("[data-metric-row]")].map((row) => {
      const meta = LAB9.metrics.find((item) => item.id === row.dataset.metricRow);
      const detectRaw = row.querySelector("[data-detect]")?.value ?? "";
      const recoverRaw = row.querySelector("[data-recover]")?.value ?? "";
      const detect = detectRaw.trim() === "" ? NaN : Number(detectRaw);
      const recover = recoverRaw.trim() === "" ? NaN : Number(recoverRaw);
      return { meta, detect, recover, ok: Number.isFinite(detect) && Number.isFinite(recover) && detect >= 0 && recover >= 0 };
    });
  }

  function renderMetrics() {
    const rows = readMetrics();
    const good = rows.filter((row) => row.ok);
    const out = root.querySelector("#metric-result");
    if (!out) return;
    if (!good.length) {
      out.textContent = "Әр жолға нөлден басталатын минут жазыңыз.";
      return;
    }
    const detectSum = good.reduce((sum, row) => sum + row.detect, 0);
    const recoverSum = good.reduce((sum, row) => sum + row.recover, 0);
    const n = good.length;
    const mttd = detectSum / n;
    const mttr = recoverSum / n;
    const detectList = good.map((row) => row.detect).join(" + ");
    const recoverList = good.map((row) => row.recover).join(" + ");
    const late = good.filter((row) => row.detect > LAB9.detectTarget).map((row) => row.meta.id);
    const slow = good.filter((row) => row.recover > row.meta.target).map((row) => `${row.meta.id} (${row.meta.targetText})`);
    const detectGap = late.length ? `15 минуттан ұзақ: ${late.join(", ")}.` : "Әр жолдың анықтауы 15 минутқа сыяды.";
    const recoverGap = slow.length ? `Өз мақсатынан ұзақ: ${slow.join(", ")}.` : "Әр жол өз қалпына келтіру мақсатына сыяды.";
    out.innerHTML = `
      <p><strong>MTTD</strong> = (${detectList}) / ${n} = ${lab9FmtMin(mttd)}. Мақсат: сыни және жоғары үшін 15 мин. ${detectGap}</p>
      <p><strong>MTTR</strong> = (${recoverList}) / ${n} = ${lab9FmtMin(mttr)}. ${recoverGap}</p>`;
  }

  root.addEventListener("click", (event) => {
    const step = event.target.closest("[data-step]");
    if (step && !step.disabled) {
      const item = LAB9.incidents.find((row) => row.n === step.dataset.inc);
      const next = item ? Number(item[step.dataset.step]) + Number(step.dataset.dir) : 0;
      if (item && next >= 1 && next <= 3) {
        item[step.dataset.step] = String(next);
        lab9Sync(item);
        paintIncident(item);
        paintMatrix();
        paintCounts();
        applyIncidents(filterMode, filterValue);
      }
      return;
    }
    const inc = event.target.closest("[data-inc-filter]");
    if (inc) {
      const value = inc.dataset.incFilter;
      applyIncidents(value === "all" ? "all" : "prio", value);
      return;
    }
    const cell = event.target.closest("#prio-grid [data-cell]");
    if (cell) {
      applyIncidents("cell", cell.dataset.cell);
      return;
    }
    const scenario = event.target.closest("[data-scenario-filter]");
    if (scenario) applyScenario(scenario.dataset.scenarioFilter);
  });

  root.addEventListener("input", (event) => {
    if (event.target.closest("[data-metric-row]")) renderMetrics();
  });

  renderMetrics();
}

