function lab4LifeSvg() {
  const rows = [
    ["Қабылдау", ["Басшы рөл сұрайды", "Әкімші тіркелгі ашады", "MFA байланады"]],
    ["Ауыстыру", ["Ескі рөл жабылады", "Басшы жаңасын бекітеді", "Сессия үзіледі"]],
    ["Шығару", ["Тіркелгі бұғатталады", "Келесі күні жойылады", "Аудитор тексереді"]],
  ];
  const boxW = 210;
  const boxH = 50;
  const gapX = 40;
  const originX = 168;
  const rowY = [24, 150, 276];
  let edges = "";
  let nodes = "";
  rows.forEach((row, index) => {
    const y = rowY[index];
    row[1].forEach((label, step) => {
      const x = originX + step * (boxW + gapX);
      const mid = y + boxH / 2;
      nodes += `<g class="d-node"><rect x="${x}" y="${y}" width="${boxW}" height="${boxH}" rx="12" /><text x="${x + boxW / 2}" y="${mid}">${label}</text></g>`;
      if (step < row[1].length - 1) {
        const next = x + boxW + gapX;
        edges += `<path class="d-edge" d="M ${x + boxW} ${mid} L ${next} ${mid}" />`;
      }
    });
  });
  const labels = rows
    .map((row, index) => `<text class="d-label" x="12" y="${rowY[index] + boxH / 2}">${row[0]}</text>`)
    .join("");
  const width = originX + 3 * boxW + 2 * gapX + 24;
  const height = rowY[2] + boxH + 24;
  return `
    <svg class="dep-svg" viewBox="0 0 ${width} ${height}" role="img" aria-label="Есептік жазбаның өмірлік циклі">
      <defs>
        <marker id="lab4-arrow" viewBox="0 0 10 10" markerWidth="14" markerHeight="14" refX="9" refY="5" orient="auto" markerUnits="userSpaceOnUse">
          <path d="M 0 1 L 10 5 L 0 9 Z" fill="#0d5c4b" />
        </marker>
      </defs>
      ${labels}
      ${edges}
      ${nodes}
    </svg>`;
}

